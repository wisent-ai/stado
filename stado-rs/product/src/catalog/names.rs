//! `stado product catalog --names [ORG]`: the name register (`~/NAMES.md`),
//! one row per active repository of the organization as GitHub lists it,
//! with the product the catalog claims it for and what it is: the
//! repository's own GitHub description, or, when GitHub has none, what the
//! catalog says it is (the claiming product's description for its owner
//! repository, and for any other claimed repository its surface kind and
//! product before that description), each row naming which source it read.
//! A deleted or archived repository leaves the register the next time it is
//! generated; a repository described by neither is listed anyway, because a
//! name nobody can look up is the failure the register exists to prevent.

use crate::common::checked;
use anyhow::{Context, Result};
use serde_json::Value;
use std::collections::BTreeMap;
use std::process::Command;

const PREAMBLE: &str = "# Wisent name register

Generated by `stado product catalog --names --output ~/NAMES.md` from the
organization's repositories on GitHub and Stado's product catalog. Do not edit
by hand: change the repository's description on GitHub, or the product's record
through `stado product registry`, then regenerate. A row whose GitHub
description is empty says what the catalog says it is: a product's owner
repository carries the product's description, and any other repository the
product claims carries its surface kind and product before that description
(\"desktop surface of `weles`: ...\"). The `from` column says which source it is.

**These are product names, not words.** Nearly all of them are ordinary Polish
nouns. `brama` is not \"gate\", `oko` is not \"eye\", `most` is not \"bridge\", `las`
is not \"forest\", `stado` is not \"herd\", `skarbiec` is not \"vault\", `jeden` is
not \"one\", `tama` is not \"dam\", `probierz` is not \"touchstone\". If a sentence
still makes sense after you translate one of these, you have misread it.

When the user names something you do not recognise, look it up here before
answering. An answer built on a guessed name is wrong even when it is coherent.

This is the canonical register of **names**, not the canonical list of products.
Product identity, status, owner and surfaces live in
`stado/catalog/products.yml`. A repository appearing below does not make it a
product; the product column names the catalog record that claims it.

Each name is a repository as GitHub names it, not a directory on this machine:
a local directory can be called anything, so a directory name is not evidence
of what a repository is.

| name | product | what it is | from |
|---|---|---|---|
";

/// A catalog product that claims a repository: its id, its description and
/// the kinds of surface the repository is, none when it is the product's
/// owner repository.
struct Claim {
    id: String,
    description: String,
    surfaces: Vec<String>,
}

impl Claim {
    /// What the catalog says the repository is: the owner repository is the
    /// product and carries its description; any other claimed repository is
    /// one of its surfaces, named with its kind before the description, so a
    /// desktop app or client library never reads as the product itself.
    fn described(&self) -> Option<String> {
        let description = self.description.trim();
        if description.is_empty() {
            return None;
        }
        Some(match self.surfaces.is_empty() {
            true => description.to_owned(),
            false => format!(
                "{} surface of `{}`: {description}",
                self.surfaces.join(" and "),
                self.id
            ),
        })
    }
}

/// Which catalog product claims each repository (`owner/name`), and as what.
fn owners(document: &Value) -> Result<BTreeMap<String, Claim>> {
    let mut owners = BTreeMap::new();
    for product in document["products"]
        .as_array()
        .context("products must be a list")?
    {
        let id = super::text(product, "id")?;
        let description = super::text(product, "description")?;
        let owner = super::text(product, "owner_repository")?;
        owners.insert(
            owner.to_owned(),
            Claim {
                id: id.to_owned(),
                description: description.to_owned(),
                surfaces: Vec::new(),
            },
        );
        for surface in product["surfaces"]
            .as_array()
            .context("surfaces must be a list")?
        {
            let repository = super::text(surface, "repository")?;
            if repository == owner {
                continue;
            }
            let kind = super::text(surface, "kind")?;
            let claim = owners
                .entry(repository.to_owned())
                .or_insert_with(|| Claim {
                    id: id.to_owned(),
                    description: description.to_owned(),
                    surfaces: Vec::new(),
                });
            if claim.id == id && !claim.surfaces.iter().any(|known| known == kind) {
                claim.surfaces.push(kind.to_owned());
            }
        }
    }
    Ok(owners)
}

fn cell(text: &str) -> String {
    text.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

/// The register for `org`, as Markdown.
pub fn register(document: &Value, org: &str) -> Result<String> {
    let output = checked(Command::new("gh").args([
        "repo",
        "list",
        org,
        "--limit",
        "10000",
        "--json",
        "nameWithOwner,name,description,isArchived",
    ]))?;
    let mut repositories: Vec<Value> = serde_json::from_slice(&output.stdout)
        .context("gh repo list answered something other than a JSON list")?;
    repositories.retain(|repository| repository["isArchived"] != true);
    repositories.sort_by(|a, b| a["name"].as_str().cmp(&b["name"].as_str()));
    let owners = owners(document)?;
    let mut register = PREAMBLE.to_owned();
    for repository in &repositories {
        let name = repository["name"]
            .as_str()
            .context("a repository has no name")?;
        let full = repository["nameWithOwner"].as_str().with_context(|| {
            format!("gh repo list gave repository {name} no nameWithOwner, so the catalog claim on it cannot be looked up")
        })?;
        let claim = owners.get(full);
        let product = match claim {
            Some(claim) => format!("`{}`", claim.id),
            None => String::new(),
        };
        let github = repository["description"]
            .as_str()
            .map(str::trim)
            .filter(|text| !text.is_empty());
        let catalog = claim.and_then(Claim::described);
        let (description, from) = match (github, catalog) {
            (Some(text), _) => (cell(text), "GitHub"),
            (None, Some(text)) => (cell(&text), "catalog"),
            (None, None) => (
                "(no description on GitHub or in the catalog)".to_owned(),
                "",
            ),
        };
        register.push_str(&format!(
            "| `{name}` | {product} | {description} | {from} |\n"
        ));
    }
    Ok(register)
}
